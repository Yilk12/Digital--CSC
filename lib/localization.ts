// Translation function
export function t(key: string, language: SupportedLanguage = "en"): string {
  const translation = translations[key]
  if (!translation) {
    console.warn(`Translation key "${key}" not found`)
    return key
  }

  return translation[language] || translation.en || key
}

// Get language configuration
export function getLanguageConfig(code: SupportedLanguage): LanguageConfig {
  return supportedLanguages.find((lang) => lang.code === code) || supportedLanguages[0]
}

// Format date according to language
export function formatDate(date: Date | string, language: SupportedLanguage = "en"): string {
  const dateObj = typeof date === "string" ? new Date(date) : date

  const options: Intl.DateTimeFormatOptions = {
    year: "numeric",
    month: "long",
    day: "numeric",
  }

  // Use appropriate locale for each language
  const localeMap: Record<SupportedLanguage, string> = {
    en: "en-US",
    am: "am-ET",
    or: "om-ET",
    ti: "ti-ET",
    so: "so-ET",
    sid: "en-US", // Fallback
    wo: "en-US", // Fallback
    aa: "en-US",
    har: "en-US",
    slt: "en-US",
    sgg: "en-US",
    hdy: "en-US",
    ktb: "en-US",
    gmo: "en-US",
    gof: "en-US",
    ged: "en-US",
    bcq: "en-US",
    kbr: "en-US",
    she: "en-US",
    guk: "en-US",
    nus: "en-US",
    anu: "en-US",
    agj: "en-US",
  }

  try {
    return dateObj.toLocaleDateString(localeMap[language], options)
  } catch {
    return dateObj.toLocaleDateString("en-US", options)
  }
}

